import { ApiProperty } from '@nestjs/swagger';
import { IsEnum, IsInt, IsUUID, Max, Min } from 'class-validator';
import { PlayContext } from './play-history.entity.js';

/** A day of listening; anything longer is a client bug. */
const MAX_MS_PLAYED = 86_400_000;

export class RecordPlayDto {
  @ApiProperty({ format: 'uuid', description: 'Generated by the client once per play.' })
  @IsUUID()
  playId: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  trackId: string;

  @ApiProperty({
    minimum: 0,
    maximum: MAX_MS_PLAYED,
    description: 'Time actually listened, excluding seeks.',
  })
  @IsInt()
  @Min(0)
  @Max(MAX_MS_PLAYED)
  msPlayed: number;

  @ApiProperty({ enum: PlayContext, enumName: 'PlayContext' })
  @IsEnum(PlayContext)
  context: PlayContext;
}
