import { Column, Entity, Index, JoinColumn, ManyToOne, PrimaryGeneratedColumn } from 'typeorm';
import { Track } from '../catalog/entities/track.entity.js';
import { User } from '../users/user.entity.js';

/** Where a play started, for history and future recommendations. */
export enum PlayContext {
  Album = 'album',
  Artist = 'artist',
  Playlist = 'playlist',
  Search = 'search',
  Home = 'home',
  Favorites = 'favorites',
  Other = 'other',
}

/** One row per valid play (SPEC §6.4). Rows are immutable, so `playedAt` doubles as `createdAt`. */
@Entity('play_history')
@Index('IDX_play_history_user_played_at', ['userId', 'playedAt'])
@Index('UQ_play_history_user_play', ['userId', 'playId'], { unique: true })
export class PlayHistory {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @ManyToOne(() => User, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'user_id' })
  user?: User;

  @Column({ name: 'track_id', type: 'uuid' })
  trackId: string;

  // Tracks are only soft-deleted, so history keeps pointing at them.
  @ManyToOne(() => Track, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'track_id' })
  track?: Track;

  /** Generated by the client once per play; makes the report idempotent. */
  @Column({ name: 'play_id', type: 'uuid' })
  playId: string;

  @Column({ name: 'ms_played', type: 'int' })
  msPlayed: number;

  @Column({ type: 'enum', enum: PlayContext, enumName: 'play_context' })
  context: PlayContext;

  @Column({ name: 'played_at', type: 'timestamptz', default: () => 'now()' })
  playedAt: Date;
}
